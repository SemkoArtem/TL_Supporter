//! Interface languages. Ukrainian text in the code is the lookup key.
//! English is the default, because it is the one language everybody can read.

use eframe::egui;
use std::sync::atomic::{AtomicU8, Ordering};

const LANG_FILE: &str = "language.cfg";
pub const LANGUAGES: [(&str, &str); 3] = [("en", "English"), ("uk", "Українська"), ("ru", "русский")];

static LANG: AtomicU8 = AtomicU8::new(0);

/// Reads the saved language. Called once when the program starts.
pub fn init() {
    let saved = std::fs::read_to_string(crate::util::data_dir().join(LANG_FILE)).unwrap_or_default();
    let index = LANGUAGES.iter().position(|l| l.0 == saved.trim()).unwrap_or(0);
    LANG.store(index as u8, Ordering::Relaxed);
}

pub fn set_language(index: usize) {
    LANG.store(index as u8, Ordering::Relaxed);
    let _ = std::fs::write(crate::util::data_dir().join(LANG_FILE), LANGUAGES[index].0);
}

/// Returns true when the language was changed.
pub fn language_picker(ui: &mut egui::Ui) -> bool {
    let current = LANG.load(Ordering::Relaxed) as usize;
    let mut chosen = current;
    egui::ComboBox::from_id_salt("language").width(160.0).selected_text(LANGUAGES[current].1).show_ui(ui, |ui| {
        for (i, (_, name)) in LANGUAGES.iter().enumerate() {
            ui.selectable_value(&mut chosen, i, *name);
        }
    });
    if chosen != current {
        set_language(chosen);
        ui.ctx().request_repaint();
        return true;
    }
    false
}

/// The text in the chosen language. Text that is not in the table is shown as it is.
pub fn tr<'a>(uk: &'a str) -> &'a str {
    let lang = LANG.load(Ordering::Relaxed);
    if lang == 1 {
        return uk;
    }
    match TABLE.iter().find(|row| row.0 == uk) {
        Some(row) => {
            if lang == 0 {
                row.1
            } else {
                row.2
            }
        }
        None => uk,
    }
}

